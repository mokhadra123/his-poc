export type L = { en: string; ar: string };

export async function getLang(): Promise<Lang> {
  const lang = (await cookies()).get(LANG_COOKIE)?.value;
  return lang === "ar" ? "ar" : "en";
}

export async function getDict() {
  return dict[await getLang()];
}

